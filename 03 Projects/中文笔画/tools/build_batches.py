"""Build the data the page loads, from data/batches.json (the one file to edit each week).

Writes two classic scripts, so the page works when opened from a file as well as from a server:
  data/batches.js  -> window.BATCHES  (the tabs, one per upload date, newest first)
  data/strokes.js  -> window.STROKES  (stroke outlines and order for every character in the batches)

Stroke data: hanzi-writer-data (Make Me a Hanzi, Arphic Public License; see assets/fonts/ and
assets/CREDITS.md). Get it once:  npm pack hanzi-writer-data && tar xzf hanzi-writer-data-*.tgz
Run from the project folder:  python3 tools/build_batches.py path/to/package

Weekly upload: add one object to "batches" in data/batches.json (date = the upload date,
lesson = the lesson name, items = {ch, py}), then run this script and tools/test_data.js.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')


def dump(obj):
    return json.dumps(obj, ensure_ascii=False, indent=1)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if not args:
        sys.exit(__doc__)
    folder = args[0]
    src = json.load(open(os.path.join(DATA, 'batches.json'), encoding='utf-8'))
    batches = sorted(src['batches'], key=lambda b: b['date'], reverse=True)   # newest tab first

    chars = list(dict.fromkeys(i['ch'] for b in batches for i in b['items']))
    strokes, missing = {}, []
    for c in chars:
        path = os.path.join(folder, c + '.json')
        if not os.path.exists(path):
            missing.append(c)
            continue
        d = json.load(open(path, encoding='utf-8'))
        strokes[c] = {'strokes': d['strokes'], 'medians': d['medians'], 'radStrokes': d.get('radStrokes', [])}

    with open(os.path.join(DATA, 'batches.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_batches.py from data/batches.json. Edit the JSON, not this file.\n')
        f.write('window.BATCHES = ' + dump(batches) + ';\n')
    with open(os.path.join(DATA, 'strokes.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_batches.py (hanzi-writer-data, Arphic Public License).\n')
        f.write('window.STROKES = ' + json.dumps(strokes, ensure_ascii=False, separators=(',', ':')) + ';\n')

    print(f'{len(batches)} batches, {len(chars)} characters, strokes for {len(strokes)}')
    if missing:
        print('No stroke data for:', ''.join(missing))
        sys.exit(1)


if __name__ == '__main__':
    main()
