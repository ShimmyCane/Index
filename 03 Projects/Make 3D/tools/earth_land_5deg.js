// rough desert boxes [lat low, lat high, lon low, lon high] in degrees. Land cells inside them are sand.
const DESERT_BOXES = [[15, 31, -17, 35], [16, 30, 35, 56], [37, 46, 75, 112], [-33, -18, 120, 142], [-30, -17, 12, 26], [-28, -18, -72, -68]];
const inBox = (la, lo, b) => la >= b[0] && la <= b[1] && lo >= b[2] && lo <= b[3];
// every land cell: { lat, lon, desert, ice } at the cell centre
function landCells() {
  const cells = [];
  ROWS.forEach((row, i) => {
    const lat = 87.5 - 5 * i;
    for (let j = 0; j < row.length; j++) {
      if (row[j] !== '1') continue;
      const lon = -177.5 + 5 * j;
      cells.push({ lat, lon, ice: lat <= -80, desert: lat > -80 && DESERT_BOXES.some((b) => inBox(lat, lon, b)) });
    }
  });
  return cells;
}
module.exports = { ROWS, DESERT_BOXES, landCells };
