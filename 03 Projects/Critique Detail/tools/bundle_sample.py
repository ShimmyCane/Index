#!/usr/bin/env python3
"""Write js/sample.bundle.js so index.html opens from file:// with the sample review, rulebooks and lessons.
Run after any change to the sample report, schemas/ or library/:  python3 tools/bundle_sample.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
read = lambda p: json.loads((ROOT / p).read_text(encoding="utf-8"))
data = {
    "report": read("outputs/reports/detail_sample.json"),
    "image": "inputs/detail_sample.png",
    "schemas": [read(p.relative_to(ROOT)) for p in sorted((ROOT / "schemas").glob("div_*/*.json"))],
    "lessons": read("library/lessons_learned.json")["lessons"],
}
out = ROOT / "js" / "sample.bundle.js"
out.write_text("// Generated by tools/bundle_sample.py. Do not edit by hand.\nwindow.DC_SAMPLE = "
               + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print("wrote", out.relative_to(ROOT), out.stat().st_size, "bytes")
