#!/usr/bin/env python3
"""Write js/sample.bundle.js so index.html opens from file:// with the sample reviews, rulebooks, lessons and defaults.
Run after any change to a sample report, schemas/, library/ or project_context.json:  python3 tools/bundle_sample.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
read = lambda p: json.loads((ROOT / p).read_text(encoding="utf-8"))
data = {
    "samples": [{"report": read("outputs/reports/%s.json" % n), "image": "inputs/%s.png" % n} for n in ("detail_sample", "detail_slop")],
    "schemas": [read(p.relative_to(ROOT)) for p in sorted((ROOT / "schemas").glob("div_*/*.json"))],
    "lessons": read("library/lessons_learned.json")["lessons"],
    "defaults": {k: v for k, v in read("project_context.json").items() if not k.startswith("_")},
}
out = ROOT / "js" / "sample.bundle.js"
out.write_text("// Generated by tools/bundle_sample.py. Do not edit by hand.\nwindow.DC_SAMPLE = "
               + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print("wrote", out.relative_to(ROOT), out.stat().st_size, "bytes,", len(data["schemas"]), "rulebooks")
