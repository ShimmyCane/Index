// Builds the sample from tools/diorama_scene.js: operation list -> replay -> audit.
// Writes samples/plains-diorama/{history,model}.json and js/sample_bundle.js (for file:// use).
// Refuses to write anything if the audit is not clean (no errors, no unexplained warnings).
// Run from the project folder: node tools/build_sample.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const M = require(path.join(root, 'js/core/model.js'));
const scene = require(path.join(__dirname, 'diorama_scene.js'));
const world = JSON.parse(fs.readFileSync(path.join(root, 'worlds', scene.header.world + '.json'), 'utf8'));
const story = JSON.parse(fs.readFileSync(path.join(root, 'exhibit', 'story.json'), 'utf8'));

const t0 = Date.parse('2026-11-18T10:00:00Z');
const stamp = (seq) => new Date(t0 + seq * 60000).toISOString().replace(/\.\d{3}Z$/, 'Z');
const ops = [];
let seq = 0;

for (const o of scene.objects) {
  seq++;
  const object = { uuid: o.uuid, name: o.name, type: o.type };
  if (o.description) object.description = o.description;
  if (o.parent) object.parent = o.parent;
  if (o.dimensions) object.dimensions = o.dimensions;
  if (o.position) object.position = o.position;
  if (o.material) object.material = o.material;
  for (const k of ['rotation_x', 'rotation_y', 'rotation_z']) if (o[k] !== undefined) object[k] = o[k];
  for (const k of ['joints', 'rings', 'facing']) if (o[k] !== undefined) object[k] = o[k];
  if (o.certainty) object.certainty = o.certainty;
  ops.push({ seq, op: 'add', time: stamp(seq), author: 'jimmy', note: 'add ' + o.name, object });
}
for (const f of scene.flags) {
  seq++;
  ops.push({ seq, op: 'flag', time: stamp(seq), author: 'jimmy', note: 'flag ' + f.id, id: f.id, kind: f.kind, target: f.target, text: f.text });
}

const history = { schema: M.SCHEMA.history, header: scene.header, operations: ops };
const result = M.replay(history, world);
const audit = M.audit(result);

// The story must point only at objects that exist, and cite only listed sources (or 'scene' for a scene choice).
const storyProblems = [];
const sourceIds = story.sources.map(x => x.id).concat(['scene']);
story.steps.forEach(st => {
  st.objects.forEach(u => { if (!result.model.objects.some(o => o.uuid === u)) storyProblems.push(st.id + ' points at missing object ' + u); });
  st.claims.forEach(c => { if (sourceIds.indexOf(c.source) < 0) storyProblems.push(c.id + ' cites unknown source ' + c.source); });
});
if (storyProblems.length) { console.error('Story problems:\n' + storyProblems.join('\n')); process.exit(1); }

if (result.rejected.length || !audit.ok) {
  console.error('Sample not written. Rejected operations:', JSON.stringify(result.rejected));
  console.error(result.diagnostics.filter(d => d.severity === 'error' || !d.explained).map(d => d.code + ' ' + d.path + ' ' + d.message).join('\n'));
  process.exit(1);
}

const outDir = path.join(root, 'samples', 'plains-diorama');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'history.json'), JSON.stringify(history, null, 2) + '\n');
fs.writeFileSync(path.join(outDir, 'model.json'), JSON.stringify(result.model, null, 2) + '\n');
const bundle = { history, model: result.model, world, audit, story };
fs.writeFileSync(path.join(root, 'js', 'sample_bundle.js'),
  '// Generated by tools/build_sample.js. Do not edit by hand.\nwindow.M3DXC_SAMPLE = ' + JSON.stringify(bundle) + ';\n');
const consult = M.openConsultations(result.model).length;
console.log('Sample written: ' + result.model.objects.length + ' objects, ' + result.model.flags.length + ' flags (' + consult +
  ' open for consultation), audit ok (' + audit.explained + ' warnings explained by flags), history hash ' + result.model.history_hash);
